"""Deterministic `run_workflow` multi-dimension code review orchestrator for `review-sdlc`.

Executes multi-dimension code review at max subagent depth = 1:
- Reads the manifest generated by `scripts/skill/review.js` (or invokes it).
- Fans out concurrently over `ACTIVE`/`TRUNCATED` dimensions via
  `asyncio.gather(..., return_exceptions=True)` using `research` agents, with
  graceful `not-reviewed` fallback when any dimension agent raises or fails.
- Consolidates, deduplicates, flags contradictions, and calibrates severities via
  a single `agent(..., model="flash", schema=...)` pass.
- Computes the final verdict deterministically, persists `{diff_dir}/review-comment.md`,
  and prints structured JSON for `review-sdlc` posting/cleanup gates.

Note: Uses `async def main()` / `async def run_review(wf_args=None, cwd=None, plugin_root=None)`
with no top-level `await` so `python3 -m py_compile` succeeds cleanly. Invoke via `run_workflow`:
  exec(open("<PLUGIN_ROOT>/skills/review-sdlc/workflows/review.py").read(), globals())
  await main()
"""

import asyncio
import datetime
import json
import re
import shlex
import subprocess
from pathlib import Path


DIMENSION_FINDINGS_SCHEMA = {
    "type": "object",
    "properties": {
        "no_findings": {"type": "boolean"},
        "findings": {
            "type": "array",
            "items": {
                "type": "object",
                "properties": {
                    "file": {"type": "string"},
                    "line": {"type": "string"},
                    "severity": {
                        "type": "string",
                        "enum": ["critical", "high", "medium", "low", "info"],
                    },
                    "owasp": {"type": ["string", "null"]},
                    "title": {"type": "string"},
                    "description": {"type": "string"},
                    "suggestion": {"type": "string"},
                },
                "required": ["file", "line", "severity", "title", "description", "suggestion"],
            },
        },
        "notes": {"type": ["string", "null"]},
    },
    "required": ["no_findings", "findings"],
}

CONSOLIDATED_REVIEW_SCHEMA = {
    "type": "object",
    "properties": {
        "assessment": {"type": "string"},
        "dimensions": {
            "type": "array",
            "items": {
                "type": "object",
                "properties": {
                    "name": {"type": "string"},
                    "findings": {
                        "type": "array",
                        "items": {
                            "type": "object",
                            "properties": {
                                "file": {"type": "string"},
                                "line": {"type": "string"},
                                "severity": {
                                    "type": "string",
                                    "enum": ["critical", "high", "medium", "low", "info"],
                                },
                                "owasp": {"type": ["string", "null"]},
                                "title": {"type": "string"},
                                "description": {"type": "string"},
                                "suggestion": {"type": "string"},
                                "also_flagged_by": {"type": ["string", "null"]},
                                "contradiction_note": {"type": ["string", "null"]},
                            },
                            "required": ["file", "line", "severity", "title", "description", "suggestion"],
                        },
                    },
                },
                "required": ["name", "findings"],
            },
        },
    },
    "required": ["assessment", "dimensions"],
}

INLINE_DIFF_MAX_BYTES = 64 * 1024


def _wf_log(*parts):
    fn = globals().get("log")
    if callable(fn):
        fn(*parts)
    else:
        print(*parts)


def _wf_phase(name):
    fn = globals().get("phase")
    if callable(fn):
        fn(name)
    else:
        _wf_log(f"[phase] {name}")


def _wf_args():
    raw = globals().get("args")
    return raw if isinstance(raw, dict) else {}


def _resolve_cwd(wf_args=None):
    resolved = _wf_args() if wf_args is None else (wf_args if isinstance(wf_args, dict) else {})
    if resolved.get("cwd"):
        return str(Path(resolved["cwd"]).resolve())
    return str(Path.cwd().resolve())


def _resolve_plugin_root(cwd, wf_args=None):
    resolved = _wf_args() if wf_args is None else (wf_args if isinstance(wf_args, dict) else {})
    if resolved.get("plugin_root"):
        candidate = Path(resolved["plugin_root"]).resolve()
        if (candidate / "scripts" / "skill").is_dir():
            return str(candidate)
    if "__file__" in globals():
        candidate = Path(__file__).resolve().parents[3]
        if (candidate / "scripts" / "skill").is_dir():
            return str(candidate)
    workspaces = globals().get("WORKSPACES") or ()
    for base in [cwd, *workspaces, str(Path.home() / ".gemini" / "config" / "plugins" / "lift-sdlc"), str(Path.home() / ".gemini" / "antigravity-cli" / "plugins" / "lift-sdlc")]:
        for cand in (Path(base), Path(base) / "lift-sdlc"):
            if (cand / "scripts" / "skill").is_dir():
                return str(cand.resolve())
    return str(Path(cwd).resolve())


def _resolve_path(raw_path, base_cwd):
    if not raw_path:
        return None
    p = Path(raw_path)
    if not p.is_absolute():
        cand = Path(base_cwd) / p
        if cand.is_file() or not p.is_file():
            return cand
    return p


def to_agy_model(tier):
    """Map Gemini tier or agy enum to valid agy enum: flash_lite|flash|pro|inherit."""
    if not isinstance(tier, str) or not tier.strip():
        return "flash"
    norm = tier.strip().lower()
    if norm in ("inherit", "flash_lite", "flash", "pro"):
        return norm
    if norm.endswith("-hydrogen-low") or norm.endswith("-flash-low"):
        return "flash_lite"
    if (
        re.search(r"-(hydrogen|flash)-(medium|high|xhigh)$", norm)
        or norm in ("gemini-4-hydrogen", "gemini-3.8-flash")
    ):
        return "flash"
    if re.search(r"-(neon|argon|carbon|pro)(-(low|medium|high|xhigh))?$", norm):
        return "pro"
    return "flash"


def _parse_run_command_output(raw):
    if not isinstance(raw, str):
        return 0, str(raw or ""), ""
    if "Tool is running as a background task" in raw:
        return 124, raw, "Command exceeded synchronous WaitMsBeforeAsync window"
    code_match = re.search(r"Command exited with code (-?\d+)\.", raw)
    exit_code = int(code_match.group(1)) if code_match else 0
    if "Command output:\n" in raw:
        output = raw.split("Command output:\n", 1)[1]
    elif "Command output:" in raw:
        output = raw.split("Command output:", 1)[1].lstrip("\r\n")
    else:
        output = raw
    return exit_code, output.strip(), ""


async def run_cmd(command, summary="Run shell command", cwd=None):
    """Run a shell command via call_tool('run_command', ...) with cwd scoping."""
    full_cmd = command
    if cwd and str(Path(cwd).resolve()) != str(Path.cwd().resolve()):
        full_cmd = f"cd {shlex.quote(str(cwd))} && {command}"
    _wf_log(f"[cmd] {summary}")
    try:
        raw = await call_tool(
            "run_command",
            CommandLine=full_cmd,
            WaitMsBeforeAsync=10000,
        )
        return _parse_run_command_output(raw)
    except NameError:
        proc = await asyncio.to_thread(
            subprocess.run,
            full_cmd,
            shell=True,
            cwd=cwd or None,
            capture_output=True,
            text=True,
        )
        return proc.returncode, (proc.stdout or "").strip(), (proc.stderr or "").strip()
    except Exception as exc:
        if getattr(exc, "denied", False):
            raise
        msg = getattr(exc, "message", None) or str(exc)
        return 1, "", msg


def _build_dimension_prompt(dim, scope, cwd=None):
    matched = "\n".join(dim.get("matched_files") or [])
    commit_lines = []
    for entry in dim.get("file_context") or []:
        commits = entry.get("commits") or []
        if commits:
            joined = "; ".join(f"{c.get('hash')}: {c.get('subject')}" for c in commits)
            commit_lines.append(f"- `{entry.get('file')}` — {joined}")
    commit_block = (
        "Use these to understand the author's intent:\n\n" + "\n".join(commit_lines)
        if commit_lines
        else f"No commit context available (reviewing {scope} changes — no commits to reference)."
    )

    diff_file = dim.get("diff_file")
    diff_path = _resolve_path(diff_file, cwd) if (diff_file and cwd) else (Path(diff_file) if diff_file else None)
    diff_section = ""
    if diff_path and diff_path.is_file():
        size = diff_path.stat().st_size
        if size <= INLINE_DIFF_MAX_BYTES:
            diff_section = diff_path.read_text(encoding="utf-8", errors="replace")
        else:
            diff_section = f"(Diff exceeds {INLINE_DIFF_MAX_BYTES} bytes — read `{diff_file}` directly with `read_file`.)"
    else:
        diff_section = "(Diff file unavailable.)"

    trunc_note = ""
    if dim.get("diff_truncated"):
        omitted = ", ".join(dim.get("diff_omitted_files") or [])
        trunc_note = f"\nNote: this diff is partial; omitted files: {omitted}.\n"

    return (
        f"# Code Review: {dim['name']}\n\n"
        f"## Your Role\n"
        f"You are a code reviewer focused exclusively on: {dim.get('description', '')}\n\n"
        f"## Review Instructions\n{dim.get('body', '')}\n\n"
        f"## Changed Files in Your Scope\n{matched}\n\n"
        f"## Commit Context\n{commit_block}\n\n"
        f"## Diff to Review\n{trunc_note}{diff_section}\n\n"
        f"## Default Severity\n"
        f"Unless the review instructions specify otherwise, classify findings as: {dim.get('severity', 'medium')}\n\n"
        "## Constraints\n"
        "- Review ONLY the listed files and stay strictly within this dimension's scope.\n"
        "- Do NOT fabricate issues; every finding MUST reference an exact `file` and `line`.\n"
        "- Maximum 20 findings (prioritize by severity). If none, set `no_findings: true` and `findings: []`.\n"
        "- Return structured JSON via `finish`."
    )


def _compute_verdict(counts):
    if counts["critical"] >= 1 or counts["high"] >= 3:
        return "CHANGES REQUESTED"
    if counts["high"] >= 1 or counts["medium"] >= 5:
        return "APPROVED WITH NOTES"
    return "APPROVED"


def _render_comment_markdown(manifest, consolidated_dims, not_reviewed, verdict, counts, assessment):
    today = datetime.date.today().isoformat()
    plugin_ver = manifest.get("plugin_version") or "0.0.0"
    total_findings = sum(counts.values())
    active_count = len(consolidated_dims) + len(not_reviewed)

    lines = [
        f"## Code Review — {active_count} dimension(s), {total_findings} finding(s)",
        "",
        f"> Automated review by `review-sdlc` v{plugin_ver} · {today}",
        "",
        "### Summary",
        "",
        "| Dimension | Findings | Critical | High | Medium | Low | Info |",
        "|-----------|----------|----------|------|--------|-----|------|",
    ]

    for dim in consolidated_dims:
        dc = {"critical": 0, "high": 0, "medium": 0, "low": 0, "info": 0}
        for f in dim.get("findings") or []:
            sev = f.get("severity", "medium")
            if sev in dc:
                dc[sev] += 1
        d_total = sum(dc.values())
        lines.append(
            f"| {dim['name']} | {d_total} | {dc['critical']} | {dc['high']} | {dc['medium']} | {dc['low']} | {dc['info']} |"
        )

    for nr in not_reviewed:
        lines.append(f"| {nr['name']} | not reviewed | — | — | — | — | — |")

    lines.append(
        f"| **Total** | **{total_findings}** | **{counts['critical']}** | **{counts['high']}** | **{counts['medium']}** | **{counts['low']}** | **{counts['info']}** |"
    )
    lines.extend(["", f"### Verdict: {verdict}", "", assessment])

    if not_reviewed:
        lines.append("")
        for nr in not_reviewed:
            lines.append(f"> **Not reviewed:** {nr['name']} — {nr['reason']}")

    lines.extend(["", "---", ""])

    for dim in consolidated_dims:
        findings = dim.get("findings") or []
        dc = {"critical": 0, "high": 0, "medium": 0, "low": 0, "info": 0}
        for f in findings:
            sev = f.get("severity", "medium")
            if sev in dc:
                dc[sev] += 1
        lines.append(f"### {dim['name']} — {len(findings)} finding(s)")
        lines.append("")
        if not findings:
            lines.append("No findings for this dimension.")
            lines.extend(["", "---", ""])
            continue
        lines.append("<details>")
        lines.append(
            f"<summary>{dc['critical']} critical · {dc['high']} high · {dc['medium']} medium · {dc['low']} low · {dc['info']} info</summary>"
        )
        lines.append("")
        for f in findings:
            sev_upper = str(f.get("severity", "medium")).upper()
            owasp_suffix = f" · OWASP {f['owasp']}" if f.get("owasp") else ""
            lines.append(f"#### [{sev_upper}] {f.get('title', 'Finding')}")
            lines.append(f"**File:** `{f.get('file')}:{f.get('line')}`{owasp_suffix}")
            lines.append(f.get("description", ""))
            if f.get("also_flagged_by"):
                lines.append(f"Also flagged by: {f['also_flagged_by']}.")
            if f.get("contradiction_note"):
                lines.append(f.get("contradiction_note"))
            lines.append(f"**Suggestion:** {f.get('suggestion', 'N/A')}")
            lines.append("")
        lines.append("</details>")
        lines.extend(["", "---", ""])

    return "\n".join(lines).rstrip() + "\n"


async def run_review(wf_args=None, cwd=None, plugin_root=None):
    """Run multi-dimension code review fan-out + consolidation."""
    resolved_args = _wf_args() if wf_args is None else (dict(wf_args) if isinstance(wf_args, dict) else {})
    resolved_cwd = str(Path(cwd).resolve()) if cwd else _resolve_cwd(resolved_args)
    resolved_plugin_root = (
        str(Path(plugin_root).resolve())
        if plugin_root
        else _resolve_plugin_root(resolved_cwd, resolved_args)
    )
    wf_args = resolved_args
    cwd = resolved_cwd
    plugin_root = resolved_plugin_root

    _wf_phase("Load Review Manifest")
    manifest_file = wf_args.get("manifest_file")
    manifest_path = _resolve_path(manifest_file, cwd)
    if not manifest_path or not manifest_path.is_file():
        rev_script = str(Path(plugin_root) / "scripts" / "skill" / "review.js")
        review_args = str(wf_args.get("review_args") or "").strip()
        rc, out, err = await run_cmd(
            f"node {shlex.quote(rev_script)} {review_args}".strip(),
            summary="Run review.js prepare",
            cwd=cwd,
        )
        lines = [ln.strip() for ln in out.splitlines() if ln.strip()]
        manifest_file = lines[-1] if lines else ""
        manifest_path = _resolve_path(manifest_file, cwd)
        if rc != 0 or not manifest_path or not manifest_path.is_file():
            result = {
                "status": "failed",
                "exit_code": rc,
                "error": err or out or "review.js did not produce manifest file",
            }
            print(json.dumps(result, indent=2))
            return result

    manifest_file = str(manifest_path.resolve())
    manifest = json.loads(manifest_path.read_text(encoding="utf-8"))
    scope = manifest.get("scope") or "all"
    diff_dir = manifest.get("diff_dir") or str(Path(manifest_file).parent)
    dimensions = manifest.get("dimensions") or []
    active_dims = [d for d in dimensions if d.get("status") in ("ACTIVE", "TRUNCATED")]
    skipped_count = len([d for d in dimensions if d.get("status") == "SKIPPED"])

    _wf_phase("Dimension Review Fan-Out")
    not_reviewed = []
    reviewed_results = []

    if active_dims:
        async def run_dimension(dim):
            model = to_agy_model(dim.get("model") or manifest.get("subagent_model") or "flash")
            return await agent(
                prompt=_build_dimension_prompt(dim, scope, cwd=cwd),
                schema=DIMENSION_FINDINGS_SCHEMA,
                role=f"{dim['name']} reviewer",
                type_name="research",
                workspace="inherit",
                model=model,
            )

        raw_results = await asyncio.gather(
            *(run_dimension(d) for d in active_dims),
            return_exceptions=True,
        )

        for dim, res in zip(active_dims, raw_results):
            if isinstance(res, Exception):
                not_reviewed.append({"name": dim["name"], "reason": f"Subagent exception: {str(res)[:160]}"})
            elif not isinstance(res, dict) or not isinstance(res.get("findings"), list):
                not_reviewed.append({"name": dim["name"], "reason": "Malformed subagent response"})
            else:
                reviewed_results.append({
                    "name": dim["name"],
                    "severity": dim.get("severity", "medium"),
                    "findings": res["findings"],
                    "notes": res.get("notes"),
                })

    _wf_phase("Consolidate & Critique")
    consolidated_dims = []
    assessment = "No issues found across reviewed dimensions."

    if reviewed_results:
        consolidation_prompt = (
            "Consolidate and critique these multi-dimension code review findings.\n\n"
            "Rules:\n"
            "1. Deduplicate identical issues flagged at the same `file:line` across dimensions: "
            "keep the finding in the highest-severity dimension and set `also_flagged_by` to the other dimension name(s).\n"
            "2. If two dimensions give conflicting recommendations at the same `file:line`, keep both and set "
            "`contradiction_note` to `\"Note: conflicting recommendations — manual review required.\"`.\n"
            "3. Recalibrate obviously miscalibrated severities (critical|high|medium|low|info).\n"
            "4. Preserve all dimensions (with empty `findings: []` if no findings survive).\n"
            "5. Write a concise 1-sentence overall `assessment`"
            + (f" — MUST explicitly state \"{len(not_reviewed)} dimension(s) not reviewed\"." if not_reviewed else ".")
            + f"\n\nNot reviewed dimensions: {json.dumps(not_reviewed)}\n\n"
            f"Raw per-dimension findings:\n{json.dumps(reviewed_results, indent=2)}"
        )
        try:
            cons = await agent(
                prompt=consolidation_prompt,
                schema=CONSOLIDATED_REVIEW_SCHEMA,
                role="Consolidate review findings",
                type_name="self",
                workspace="inherit",
                model="flash",
            )
            if isinstance(cons, dict) and isinstance(cons.get("dimensions"), list):
                consolidated_dims = cons["dimensions"]
                assessment = cons.get("assessment") or assessment
            else:
                raise ValueError("Malformed consolidation response")
        except Exception as exc:
            _wf_log(f"[review] consolidation agent failed, falling back to raw findings: {exc}")
            consolidated_dims = [
                {"name": d["name"], "findings": d.get("findings") or []}
                for d in reviewed_results
            ]
            nr_suffix = f" ({len(not_reviewed)} dimension(s) not reviewed)" if not_reviewed else ""
            assessment = f"Raw per-dimension findings preserved (consolidation fallback){nr_suffix}."
    elif not_reviewed:
        assessment = f"Review incomplete: {len(not_reviewed)} dimension(s) not reviewed."

    counts = {"critical": 0, "high": 0, "medium": 0, "low": 0, "info": 0}
    for dim in consolidated_dims:
        for f in dim.get("findings") or []:
            sev = str(f.get("severity", "medium")).lower()
            if sev in counts:
                counts[sev] += 1

    verdict = _compute_verdict(counts)

    _wf_phase("Persist Review Comment")
    Path(diff_dir).mkdir(parents=True, exist_ok=True)
    comment_file = str(Path(diff_dir) / "review-comment.md")
    comment_md = _render_comment_markdown(manifest, consolidated_dims, not_reviewed, verdict, counts, assessment)
    Path(comment_file).write_text(comment_md, encoding="utf-8")

    final_result = {
        "status": "completed",
        "verdict": verdict,
        "counts": counts,
        "total_findings": sum(counts.values()),
        "dimensions_run": len(active_dims),
        "dimensions_skipped": skipped_count,
        "not_reviewed": not_reviewed,
        "comment_file": comment_file,
        "diff_dir": diff_dir,
        "manifest_file": manifest_file,
        "scope": scope,
        "branch": manifest.get("current_branch"),
        "pr": manifest.get("pr") or {"exists": False},
        "plan_critique": manifest.get("plan_critique") or {},
    }
    print(json.dumps(final_result, indent=2))
    return final_result


async def main():
    """Entrypoint delegating to `run_review` using workflow `args` globals."""
    return await run_review(wf_args=_wf_args())


if __name__ == "__main__":
    try:
        asyncio.get_running_loop()
    except RuntimeError:
        asyncio.run(main())
