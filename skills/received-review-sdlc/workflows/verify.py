"""Deterministic `run_workflow` thread verification orchestrator for `received-review-sdlc`.

Verifies outstanding PR review comment threads at max subagent depth = 1:
- Reads the manifest generated by `scripts/skill/received-review.js` (or invokes it).
- Selects `outstanding` threads (intersecting raw `only_ids` when supplied).
- Groups threads by file path (chunks of max 4), assigning `pro` when any thread
  in the group has severity `critical` or `high`, else `flash`.
- Fans out concurrently over `research` agents via
  `asyncio.gather(..., return_exceptions=True)` + structured `schema` output.
- Performs 1 bounded retry pass for any missing thread IDs.
- Persists the full `<manifest>.verification.md` report and returns bounded
  verification JSON matching `scripts/lib/verify-summary.js` invariants (missing
  IDs omitted from `findings[]`, never fabricated).

Note: Uses `async def main()` with no top-level `await` so `python3 -m py_compile`
succeeds cleanly. Invoke via `run_workflow` with:
  exec(open("<PLUGIN_ROOT>/skills/received-review-sdlc/workflows/verify.py").read(), globals())
  await main()
"""

import asyncio
import datetime
import json
import re
import shlex
import subprocess
from pathlib import Path


VALID_VERIFICATION_STATUSES = {
    "confirmed",
    "confirmed-incomplete",
    "incorrect",
    "partially-correct",
    "cannot-verify",
}

MAX_THREADS_PER_GROUP = 4
MAX_EVIDENCE = 5
MAX_RIPPLE = 3
MAX_REASONING_CHARS = 240

GROUP_VERIFY_SCHEMA = {
    "type": "object",
    "properties": {
        "findings": {
            "type": "array",
            "items": {
                "type": "object",
                "properties": {
                    "id": {"type": "string"},
                    "verificationStatus": {
                        "type": "string",
                        "enum": sorted(VALID_VERIFICATION_STATUSES),
                    },
                    "evidence": {
                        "type": "array",
                        "items": {"type": "string"},
                        "maxItems": MAX_EVIDENCE,
                    },
                    "rippleEffects": {
                        "type": "array",
                        "items": {"type": "string"},
                        "maxItems": MAX_RIPPLE,
                    },
                    "reasoning": {"type": "string"},
                    "detail": {"type": "string"},
                },
                "required": ["id", "verificationStatus", "evidence", "rippleEffects", "reasoning"],
            },
        }
    },
    "required": ["findings"],
}


def _wf_log(*parts):
    fn = globals().get("log")
    if callable(fn):
        fn(*parts)
    else:
        print(*parts)


def _wf_phase(name):
    fn = globals().get("phase")
    if callable(fn):
        fn(name)
    else:
        _wf_log(f"[phase] {name}")


def _wf_args():
    raw = globals().get("args")
    return raw if isinstance(raw, dict) else {}


def _resolve_cwd():
    wf_args = _wf_args()
    if wf_args.get("cwd"):
        return str(Path(wf_args["cwd"]).resolve())
    return str(Path.cwd().resolve())


def _resolve_plugin_root(cwd):
    wf_args = _wf_args()
    if wf_args.get("plugin_root"):
        candidate = Path(wf_args["plugin_root"]).resolve()
        if (candidate / "scripts" / "skill").is_dir():
            return str(candidate)
    if "__file__" in globals():
        candidate = Path(__file__).resolve().parents[3]
        if (candidate / "scripts" / "skill").is_dir():
            return str(candidate)
    workspaces = globals().get("WORKSPACES") or ()
    for base in [cwd, *workspaces, str(Path.home() / ".gemini" / "config" / "plugins" / "lift-sdlc"), str(Path.home() / ".gemini" / "antigravity-cli" / "plugins" / "lift-sdlc")]:
        for cand in (Path(base), Path(base) / "lift-sdlc"):
            if (cand / "scripts" / "skill").is_dir():
                return str(cand.resolve())
    return str(Path(cwd).resolve())


def _parse_run_command_output(raw):
    if not isinstance(raw, str):
        return 0, str(raw or ""), ""
    if "Tool is running as a background task" in raw:
        return 124, raw, "Command exceeded synchronous WaitMsBeforeAsync window"
    code_match = re.search(r"Command exited with code (-?\d+)\.", raw)
    exit_code = int(code_match.group(1)) if code_match else 0
    if "Command output:\n" in raw:
        output = raw.split("Command output:\n", 1)[1]
    elif "Command output:" in raw:
        output = raw.split("Command output:", 1)[1].lstrip("\r\n")
    else:
        output = raw
    return exit_code, output.strip(), ""


async def run_cmd(command, summary="Run shell command", cwd=None):
    """Run a shell command via call_tool('run_command', ...) with cwd scoping."""
    full_cmd = command
    if cwd and str(Path(cwd).resolve()) != str(Path.cwd().resolve()):
        full_cmd = f"cd {shlex.quote(str(cwd))} && {command}"
    _wf_log(f"[cmd] {summary}")
    try:
        raw = await call_tool(
            "run_command",
            CommandLine=full_cmd,
            WaitMsBeforeAsync=10000,
        )
        return _parse_run_command_output(raw)
    except NameError:
        proc = await asyncio.to_thread(
            subprocess.run,
            full_cmd,
            shell=True,
            cwd=cwd or None,
            capture_output=True,
            text=True,
        )
        return proc.returncode, (proc.stdout or "").strip(), (proc.stderr or "").strip()
    except Exception as exc:
        if getattr(exc, "denied", False):
            raise
        msg = getattr(exc, "message", None) or str(exc)
        return 1, "", msg


def group_threads_by_file(threads):
    """Group threads by file path, splitting any group > MAX_THREADS_PER_GROUP into chunks."""
    by_path = {}
    for t in threads:
        by_path.setdefault(t.get("path") or "(general)", []).append(t)
    groups = []
    for path_key, items in by_path.items():
        for i in range(0, len(items), MAX_THREADS_PER_GROUP):
            groups.append((path_key, items[i : i + MAX_THREADS_PER_GROUP]))
    return groups


def model_for_group(group_threads):
    """Use `pro` if any thread in the group is `critical` or `high`, else `flash`."""
    for t in group_threads:
        sev = str(t.get("severity") or "").lower()
        if sev in ("critical", "high"):
            return "pro"
    return "flash"


def _build_verifier_prompt(group_threads, cwd, plugin_root):
    outline_script = str(Path(plugin_root) / "scripts" / "util" / "outline-file.js")
    blocks = []
    for t in group_threads:
        body = (t.get("firstComment") or {}).get("body") or ""
        blocks.append(
            f"### Thread {t['id']}\n"
            f"Path: {t.get('path')}:{t.get('line')}\n"
            f"Severity: {t.get('severity')}\n"
            f"Reviewer comment:\n{body}"
        )
    return (
        "You are verifying PR reviewer comments against the actual codebase. "
        "Check whether the reviewer's factual claim about the code is correct — do NOT decide action verdicts.\n\n"
        f"PROJECT_ROOT: {cwd}\n"
        f"PLUGIN_ROOT: {plugin_root}\n\n"
        "For each thread below:\n"
        f"1. Read the referenced file at path/line with `view_file` (if > 200 lines, run `node \"{outline_script}\" <path>` first).\n"
        "2. Trace callers/usages and check related tests or interfaces.\n"
        "3. Assign `verificationStatus`: `confirmed | confirmed-incomplete | incorrect | partially-correct | cannot-verify`.\n"
        "4. Copy each thread `id` VERBATIM, bound `evidence` (max 5 `path:line`), `rippleEffects` (max 3), and `reasoning` (<= 240 chars).\n"
        "5. Provide full technical reasoning in `detail` and return structured JSON via `finish`.\n\n"
        "Threads to verify:\n\n"
        + "\n\n".join(blocks)
    )


def _normalize_finding(raw_f):
    status = raw_f.get("verificationStatus")
    if status not in VALID_VERIFICATION_STATUSES:
        return None
    evidence = [str(e) for e in (raw_f.get("evidence") or [])][:MAX_EVIDENCE]
    ripple = [str(r) for r in (raw_f.get("rippleEffects") or [])][:MAX_RIPPLE]
    reasoning = str(raw_f.get("reasoning") or "")[:MAX_REASONING_CHARS]
    detail = str(raw_f.get("detail") or reasoning)
    return {
        "id": str(raw_f["id"]),
        "verificationStatus": status,
        "evidence": evidence,
        "rippleEffects": ripple,
        "reasoning": reasoning,
        "_detail": detail,
    }


def _collect_group_results(groups, raw_results, expected_ids, collected_by_id):
    for (_, _), res in zip(groups, raw_results):
        if isinstance(res, Exception) or not isinstance(res, dict):
            continue
        for item in res.get("findings") or []:
            if not isinstance(item, dict) or not item.get("id"):
                continue
            tid = str(item["id"])
            if tid not in expected_ids or tid in collected_by_id:
                continue
            norm = _normalize_finding(item)
            if norm:
                collected_by_id[tid] = norm


def _render_report_markdown(pr_number, selected_threads, collected_by_id, group_count):
    ts = datetime.datetime.now(datetime.timezone.utc).isoformat()
    surviving = [t for t in selected_threads if t["id"] in collected_by_id]
    lines = [
        f"# Verification Report — PR #{pr_number}",
        f"Generated: {ts} · Threads verified: {len(surviving)} · Groups: {group_count}",
        "",
    ]
    for t in surviving:
        f = collected_by_id[t["id"]]
        comment_preview = ((t.get("firstComment") or {}).get("body") or "")[:300].replace("\n", " ")
        ev_txt = ", ".join(f["evidence"]) if f["evidence"] else "none"
        rp_txt = ", ".join(f["rippleEffects"]) if f["rippleEffects"] else "none"
        lines.extend([
            f"## {t['id']} — {t.get('path')}:{t.get('line')} — {f['verificationStatus']}",
            f"**Reviewer said:** {comment_preview}",
            f"**Evidence:** {ev_txt}",
            f"**Ripple effects:** {rp_txt}",
            f"**Detail:** {f['_detail']}",
            "",
        ])
    return "\n".join(lines).rstrip() + "\n"


async def main():
    """Verify outstanding PR review threads grouped by file with 1 retry for missing IDs."""
    wf_args = _wf_args()
    cwd = _resolve_cwd()
    plugin_root = _resolve_plugin_root(cwd)

    _wf_phase("Load Thread Manifest")
    manifest_file = wf_args.get("manifest_file")
    if not manifest_file or not Path(manifest_file).is_file():
        rr_script = str(Path(plugin_root) / "scripts" / "skill" / "received-review.js")
        rr_args = str(wf_args.get("received_review_args") or "").strip()
        rc, out, err = await run_cmd(
            f"node {shlex.quote(rr_script)} --output-file {rr_args}".strip(),
            summary="Run received-review.js prepare",
            cwd=cwd,
        )
        lines = [ln.strip() for ln in out.splitlines() if ln.strip()]
        manifest_file = lines[-1] if lines else ""
        if rc != 0 or not manifest_file or not Path(manifest_file).is_file():
            result = {
                "status": "failed",
                "exit_code": rc,
                "error": err or out or "received-review.js failed to produce manifest",
            }
            print(json.dumps(result, indent=2))
            return result

    manifest = json.loads(Path(manifest_file).read_text(encoding="utf-8"))
    pr_meta = manifest.get("pr") or {}
    pr_number = pr_meta.get("number") or "unknown"

    only_ids_raw = wf_args.get("only_ids")
    only_ids_set = None
    if isinstance(only_ids_raw, list) and only_ids_raw:
        only_ids_set = {str(x) for x in only_ids_raw}
    elif isinstance(only_ids_raw, str) and only_ids_raw.strip() and only_ids_raw.strip().lower() != "none":
        only_ids_set = {x.strip() for x in only_ids_raw.split(",") if x.strip()}

    outstanding = [t for t in (manifest.get("threads") or []) if t.get("status") == "outstanding"]
    if only_ids_set is not None:
        selected = [t for t in outstanding if str(t.get("id")) in only_ids_set]
    else:
        selected = outstanding

    expected_ids = {str(t["id"]) for t in selected}
    report_file = (
        re.sub(r"\.json$", "", manifest_file) + ".verification.md"
        if manifest_file.endswith(".json")
        else manifest_file + ".verification.md"
    )

    if not selected:
        Path(report_file).write_text(_render_report_markdown(pr_number, [], {}, 0), encoding="utf-8")
        result = {
            "status": "completed",
            "reportFile": report_file,
            "pr": pr_meta,
            "groupsDispatched": 0,
            "threadsSelected": 0,
            "missingIds": [],
            "findings": [],
        }
        print(json.dumps(result, indent=2))
        return result

    _wf_phase("Verify Thread Groups")
    groups = group_threads_by_file(selected)
    initial_group_count = len(groups)

    async def verify_group(path_key, gthreads):
        m = model_for_group(gthreads)
        return await agent(
            prompt=_build_verifier_prompt(gthreads, cwd, plugin_root),
            schema=GROUP_VERIFY_SCHEMA,
            role=f"Verify {path_key} ({len(gthreads)} thread(s))",
            type_name="research",
            workspace="inherit",
            model=m,
        )

    raw_results = await asyncio.gather(
        *(verify_group(pk, gt) for pk, gt in groups),
        return_exceptions=True,
    )

    collected_by_id = {}
    _collect_group_results(groups, raw_results, expected_ids, collected_by_id)

    missing_threads = [t for t in selected if str(t["id"]) not in collected_by_id]
    if missing_threads:
        _wf_phase("Retry Missing Thread IDs")
        retry_groups = group_threads_by_file(missing_threads)
        retry_results = await asyncio.gather(
            *(verify_group(pk, gt) for pk, gt in retry_groups),
            return_exceptions=True,
        )
        _collect_group_results(retry_groups, retry_results, expected_ids, collected_by_id)

    _wf_phase("Persist Report")
    Path(report_file).write_text(
        _render_report_markdown(pr_number, selected, collected_by_id, initial_group_count),
        encoding="utf-8",
    )

    findings = []
    missing_ids = []
    for t in selected:
        tid = str(t["id"])
        if tid in collected_by_id:
            entry = dict(collected_by_id[tid])
            entry.pop("_detail", None)
            findings.append(entry)
        else:
            missing_ids.append(tid)

    if not missing_ids:
        status = "completed"
    elif findings:
        status = "partial"
    else:
        status = "failed"

    result = {
        "status": status,
        "reportFile": report_file,
        "pr": pr_meta,
        "groupsDispatched": initial_group_count,
        "threadsSelected": len(selected),
        "missingIds": missing_ids,
        "findings": findings,
    }
    print(json.dumps(result, indent=2))
    return result


if __name__ == "__main__":
    asyncio.run(main())
